import { describe, expect, test } from 'bun:test';
import { edtfRange, sameDates } from './edtf.js';

describe('edtfRange', () => {
  const r = (v) => { const x = edtfRange(v); return x && `${x.start ?? '..'}|${x.end ?? '..'}`; };
  test.each([
    ['193-', '1930-01-01|1939-12-31'],
    ['193X?', '1930-01-01|1939-12-31'],
    ['1930s', '1930-01-01|1939-12-31'],
    ['19--', '1900-01-01|1999-12-31'],
    ['19XX~', '1900-01-01|1999-12-31'],
    ['1948-07-14', '1948-07-14|1948-07-14'],
    ['July 14, 1948', '1948-07-14|1948-07-14'],
    ['1959-09', '1959-09-01|1959-09-30'],
    ['September 1959', '1959-09-01|1959-09-30'],
    ['1960-02', '1960-02-01|1960-02-29'],
    ['ca. 1950', '1950-01-01|1950-12-31'],
    ['1950~', '1950-01-01|1950-12-31'],
    ['[1950?]', '1950-01-01|1950-12-31'],
    ['1919?/1949?', '1919-01-01|1949-12-31'],
    ['1919 - 1949', '1919-01-01|1949-12-31'],
    ['1919–1949', '1919-01-01|1949-12-31'],
    ['1919-1949', '1919-01-01|1949-12-31'],
    ['between 1919 and 1949', '1919-01-01|1949-12-31'],
    ['1906?/..', '1906-01-01|..'],
    ['after 1906', '1906-01-01|..'],
    ['../1850?', '..|1850-12-31'],
    ['before 1850', '..|1850-12-31'],
    ['1985-XX-XX', '1985-01-01|1985-12-31'],
    ['2001-21', '2001-03-01|2001-05-31'],
    ['[1667,1668]', '1667-01-01|1668-12-31'],
    ['1667 or 1668', '1667-01-01|1668-12-31'],
    ['not a date', null],
    ['', null],
  ])('%s', (input, expected) => expect(r(input)).toBe(expected));
});

describe('sameDates', () => {
  test('different notations for the same span match', () => {
    expect(sameDates('193-', '193X?')).toBe(true);
    expect(sameDates('1930s', '193X')).toBe(true);
    expect(sameDates('ca. 1950', '1950~')).toBe(true);
    expect(sameDates('July 14, 1948', '1948-07-14')).toBe(true);
  });
  test('different spans or precision do not', () => {
    expect(sameDates('1935', '193X')).toBe(false);
    expect(sameDates('1950', '1950-01')).toBe(false);
    expect(sameDates('194X?', '1935')).toBe(false);
  });
});
